#!/usr/bin/env python3
"""Merge benchmark summaries into the contest report (markdown + json).

    make_report.py --summary baseline=out/base/summary.json \
                   --summary candidate=out/cand/summary.json \
                   --summary cpu=out/cpu/summary.json \
                   --baseline baseline --out report.md

Scoring follows the published structure: 4 points of hard gates, 14 points of
build speed-up (linear between 1.0x = 0 and 2.0x = full) and 2 points of query
throughput. The query curve is not published, so it is reported as a ratio and
scored with the same 1.0x -> 2.0x shape as a conservative estimate.
"""

from __future__ import annotations

import argparse
import json
import pathlib

FULL_MARK_BUILD = 2.0
FULL_MARK_QUERY = 2.0


def load(path: str) -> dict:
    return json.loads(pathlib.Path(path).read_text())


def clamp(value: float, low: float = 0.0, high: float = 1.0) -> float:
    return max(low, min(high, value))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--summary", action="append", default=[], metavar="LABEL=PATH")
    parser.add_argument("--baseline", default="baseline")
    parser.add_argument("--out", default="report.md")
    parser.add_argument("--out-json", default="")
    parser.add_argument("--gpu", default="AMD Radeon (ROCm + hipVS)")
    parser.add_argument("--cpu", default="host CPU")
    args = parser.parse_args()

    runs: dict[str, dict] = {}
    for item in args.summary:
        label, _, path = item.partition("=")
        runs[label] = load(path)
    if not runs:
        raise SystemExit("no --summary given")
    baseline = runs.get(args.baseline)

    lines: list[str] = []
    lines.append("# seekdb × hipVS / CAGRA build report\n")
    lines.append("Generated by `tools/bench/make_report.py` from the raw `summary.json` files.\n")
    lines.append("## Environment\n")
    lines.append(f"- GPU: {args.gpu}")
    lines.append(f"- CPU: {args.cpu}")
    first = next(iter(runs.values()))
    lines.append(f"- vectors: n={first['n']} dim={first['dim']} topk={first['topk']} queries={first['nq']}")
    lines.append(f"- rounds per configuration: {len(first['rounds'])} (median reported)\n")

    lines.append("## Build performance (cold start, median of rounds)\n")
    lines.append("| config | backend | build [s] | DDL [s] | first query [s] | vs baseline |")
    lines.append("|---|---|---:|---:|---:|---:|")
    for label, run in runs.items():
        speedup = ""
        if baseline and label != args.baseline and run["median_build_seconds"] > 0:
            speedup = f"**{baseline['median_build_seconds'] / run['median_build_seconds']:.2f}x**"
        elif baseline and label == args.baseline:
            speedup = "1.00x"
        lines.append(
            f"| {label} | {run['lib']} | {run['median_build_seconds']:.3f} | "
            f"{run.get('median_ddl_seconds', 0):.3f} | "
            f"{run['rounds'][0].get('first_query_seconds', 0):.3f} | {speedup} |"
        )
    lines.append("")

    if any("query" in run["rounds"][0] for run in runs.values()):
        lines.append("## Retrieval quality and query throughput\n")
        lines.append("| config | Recall@10 | Recall@100 | QPS | P50 [ms] | P95 [ms] | QPS vs baseline |")
        lines.append("|---|---:|---:|---:|---:|---:|---:|")
        for label, run in runs.items():
            ratio = ""
            if baseline and label != args.baseline and run.get("qps"):
                ratio = f"{run['qps'] / baseline['qps']:.3f}x" if baseline.get("qps") else ""
            lines.append(
                f"| {label} | {run.get('recall_at_10', 0):.4f} | {run.get('recall_at_100', 0):.4f} | "
                f"{run.get('qps', 0):.2f} | {run.get('p50_ms', 0):.3f} | {run.get('p95_ms', 0):.3f} | {ratio} |"
            )
        lines.append("")

    lines.append("## Hard gates\n")
    gates = []
    if baseline:
        build_speedup = baseline["median_build_seconds"] / max(
            runs[args.baseline]["median_build_seconds"], 1e-9)
        for label, run in runs.items():
            if label == args.baseline:
                continue
            recall10_drop = baseline.get("recall_at_10", 0) - run.get("recall_at_10", 0)
            recall100_drop = baseline.get("recall_at_100", 0) - run.get("recall_at_100", 0)
            qps_ratio = (run.get("qps", 0) / baseline["qps"]) if baseline.get("qps") else 1.0
            served = all(r.get("trace", {}).get("cuvs_serve", 0) > 0
                         for r in run["rounds"]) if run["lib"] == "cuvs" else True
            gates.append((label, recall10_drop, recall100_drop, qps_ratio, served))
        lines.append("| config | Recall@10 drop | Recall@100 drop | QPS ratio | GPU CAGRA served |")
        lines.append("|---|---:|---:|---:|---|")
        for label, d10, d100, qps_ratio, served in gates:
            lines.append(f"| {label} | {d10:+.4f} | {d100:+.4f} | {qps_ratio:.3f}x | {'yes' if served else 'NO'} |")
        lines.append("")
        lines.append("- Gate: recall drop must stay within 0.005 and QPS must stay >= 90% of the baseline.")
        lines.append("")

    lines.append("## Score estimate\n")
    lines.append("| config | build speed-up | build points /14 | query points /2 | total /20 |")
    lines.append("|---|---:|---:|---:|---:|")
    for label, run in runs.items():
        if label == args.baseline:
            continue
        speedup = baseline["median_build_seconds"] / max(run["median_build_seconds"], 1e-9) if baseline else 1.0
        build_points = 14.0 * clamp((speedup - 1.0) / (FULL_MARK_BUILD - 1.0))
        qps_ratio = (run.get("qps", 0) / baseline["qps"]) if baseline and baseline.get("qps") else 1.0
        query_points = 2.0 * clamp((qps_ratio - 1.0) / (FULL_MARK_QUERY - 1.0))
        total = 4.0 + build_points + query_points
        lines.append(
            f"| {label} | {speedup:.2f}x | {build_points:.3f} | {query_points:.3f} | **{total:.3f}** |"
        )
    lines.append("")
    lines.append("Local numbers are indicative only: the official grader rebuilds from source and "
                 "re-runs the frozen baseline on its own machine.\n")

    pathlib.Path(args.out).write_text("\n".join(lines) + "\n")
    if args.out_json:
        pathlib.Path(args.out_json).write_text(json.dumps(runs, indent=2) + "\n")
    print(f"report written to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
